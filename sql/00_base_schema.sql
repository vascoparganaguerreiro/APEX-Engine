-- 00: BASE SCHEMA - RECONSTRUCTION, FOR NEW / STAGING DATABASES ONLY.
--
-- !! DO NOT RUN THIS AGAINST THE EXISTING PRODUCTION DATABASE. !!
--
-- What this is: the tables that migrations 01-04 created (they came from the older Streamlit app that shares the
-- production database and were never committed here: profiles, daily_metrics, activities, races, weekly_summaries,
-- intervals_connections, incl. the activity notes / AI summaries that 04_activity_notes.sql added).
-- It was NOT taken from production. It was reconstructed from how this app's code (app/, lib/, components/) reads
-- and writes the database and from what 05-08 assume already exists. Production may have more columns, other
-- types, other defaults, other constraint/index names and other policies. Lines marked "-- GUESS" are types or
-- defaults the code does not determine.
--
-- Replace it with the real thing as soon as someone has production access, e.g.:
--   supabase db dump --db-url "$PROD_DB_URL" --schema public -f 00_base_schema.sql
-- or
--   pg_dump --schema-only --schema=public --no-owner --no-privileges "$PROD_DB_URL" > 00_base_schema.sql
-- (then cut out what 05-08 create, so they keep applying on top of it).
--
-- Run order on an empty Supabase project: 00_base_schema.sql, 05, 06, 07, then optionally 08.
-- It refuses to run if any of its tables already exists, so it cannot silently re-open RLS that 07 locked down.

do $$
declare t text;
begin
  foreach t in array array['profiles','daily_metrics','activities','races','weekly_summaries','intervals_connections'] loop
    if to_regclass('public.' || t) is not null then
      raise exception '00_base_schema.sql: public.% already exists. This file is only for an EMPTY database (never production).', t;
    end if;
  end loop;
end $$;

-- ------------------------------------------------------------------ profiles (one row per auth user)
-- Read as .from("profiles").select("timezone").eq("id", uid) and .select("sleep_goal_h").maybeSingle().
-- No row is required: the code falls back to UTC and to a default sleep goal.
create table public.profiles (
  id           uuid primary key references auth.users(id) on delete cascade,
  timezone     text,                                    -- GUESS: IANA name, e.g. 'Europe/Berlin'; null -> code uses UTC
  sleep_goal_h numeric,                                 -- GUESS: numeric hours, e.g. 7.5
  created_at   timestamptz not null default now()       -- GUESS: not read by this app
);

-- ------------------------------------------------------------------ daily_metrics (one row per user and day)
-- Written by apply_manual_metrics / apply_synced_metrics (06), which use ON CONFLICT (user_id, day).
-- 06 adds the *_source columns and the check constraint, and drops NOT NULL on hrv_ms/rhr_bpm/sleep_minutes
-- (production may have had NOT NULL there; here they are nullable from the start, which 06 tolerates).
create table public.daily_metrics (
  id            bigint generated by default as identity primary key,   -- GUESS: surrogate key; the app never reads it
  user_id       uuid not null references auth.users(id) on delete cascade,
  day           date not null,
  hrv_ms        numeric,                                -- GUESS: numeric (HRV can be fractional)
  rhr_bpm       numeric,                                -- GUESS: numeric (code writes whole numbers)
  sleep_minutes numeric,                                -- GUESS: numeric (code writes whole numbers)
  sleep_score   numeric,                                -- GUESS: numeric (code writes whole numbers)
  source        text,                                   -- row-level origin: 'manual' | 'intervals' | legacy values; GUESS: no check, no default
  created_at    timestamptz not null default now(),     -- GUESS: not read by this app
  constraint daily_metrics_user_id_day_key unique (user_id, day)
);

-- ------------------------------------------------------------------ activities
-- Read: id,started_at,sport,title,duration_s,distance_m,avg_hr,load,note,ai_summary,ai_summary_at.
-- Written by the Intervals sync (upsert on user_id,source,external_id) and by note / AI-summary updates.
-- external_id and the (user_id, source, external_id) unique key are added by 05_intervals.sql.
create table public.activities (
  id            bigint generated by default as identity primary key,   -- GUESS: bigint identity (code treats id as a number)
  user_id       uuid not null references auth.users(id) on delete cascade,
  source        text,                                   -- 'intervals' for synced rows; GUESS: nullable, no default (05 also adds it if missing)
  started_at    timestamptz not null,
  sport         text not null,                          -- 'run' | 'bike' | 'swim' | 'strength' | 'other'; GUESS: no check constraint
  title         text,
  duration_s    integer,                                -- GUESS: integer seconds
  distance_m    numeric,                                -- GUESS: numeric metres
  avg_hr        integer,                                -- GUESS: integer bpm
  load          numeric,                                -- GUESS: numeric (training load / TSS, code writes whole numbers)
  note          text,                                   -- from 04_activity_notes.sql
  ai_summary    text,                                   -- from 04_activity_notes.sql
  ai_summary_at timestamptz,                            -- from 04_activity_notes.sql
  created_at    timestamptz not null default now()      -- GUESS: not read by this app
);
create index activities_user_started_idx on public.activities (user_id, started_at desc);   -- GUESS: index name/shape
create index activities_user_ai_summary_at_idx on public.activities (user_id, ai_summary_at); -- GUESS: daily AI limit count

-- ------------------------------------------------------------------ races
-- Read as .from("races").select("name,race_date").gte("race_date", day).order("race_date").limit(1).
create table public.races (
  id         bigint generated by default as identity primary key,      -- GUESS
  user_id    uuid not null references auth.users(id) on delete cascade,
  name       text not null,
  race_date  date not null,
  created_at timestamptz not null default now()         -- GUESS: not read by this app
);
create index races_user_date_idx on public.races (user_id, race_date);    -- GUESS

-- ------------------------------------------------------------------ weekly_summaries (from 04_activity_notes.sql)
-- Upserted with onConflict "user_id,week_start"; read by week_start; counted by created_at for the daily AI limit.
create table public.weekly_summaries (
  user_id    uuid not null references auth.users(id) on delete cascade,
  week_start date not null,                             -- Monday of the week
  summary    text not null,
  created_at timestamptz not null default now(),
  primary key (user_id, week_start)                     -- GUESS: may be a unique constraint next to a surrogate id in production
);

-- ------------------------------------------------------------------ intervals_connections (one per user)
-- Upserted by the server (service role) with onConflict "user_id". api_key is the legacy plaintext column that
-- 07 makes nullable and the server empties; browsers may only read user_id, athlete_id, last_sync_at, created_at.
create table public.intervals_connections (
  user_id      uuid primary key references auth.users(id) on delete cascade,
  athlete_id   text not null,
  api_key      text not null,                           -- legacy plaintext; 07 drops NOT NULL
  last_sync_at timestamptz,
  created_at   timestamptz not null default now()
);

-- ------------------------------------------------------------------ row level security: every row belongs to its owner
-- One broad "own_rows" policy per table, as in production's base schema (07 removes it from intervals_connections
-- again and replaces it with a read-only policy).
alter table public.profiles              enable row level security;
alter table public.daily_metrics         enable row level security;
alter table public.activities            enable row level security;
alter table public.races                 enable row level security;
alter table public.weekly_summaries      enable row level security;
alter table public.intervals_connections enable row level security;

create policy "own_rows" on public.profiles for all to authenticated
  using (id = (select auth.uid())) with check (id = (select auth.uid()));
create policy "own_rows" on public.daily_metrics for all to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy "own_rows" on public.activities for all to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy "own_rows" on public.races for all to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy "own_rows" on public.weekly_summaries for all to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy "own_rows" on public.intervals_connections for all to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

-- Signed-in users get plain CRUD (RLS still limits it to their own rows); anonymous visitors get nothing.
-- service_role keeps Supabase's default privileges and bypasses RLS (used by the server for intervals_connections).
revoke all on public.profiles, public.daily_metrics, public.activities, public.races, public.weekly_summaries,
              public.intervals_connections from public, anon, authenticated;
grant select, insert, update, delete on public.profiles, public.daily_metrics, public.activities, public.races,
              public.weekly_summaries, public.intervals_connections to authenticated;
